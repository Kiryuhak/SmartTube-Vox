import test from 'node:test';
import assert from 'node:assert/strict';
import { structuredEvents, safeContext } from '../src/triage.mjs';

/**
 * Gate D: Offline Contract Boundary and Negative Controls Test
 * PROMPT №163-R16 (Contract Boundary between Android Client and Worker Diagnostics).
 *
 * Test Objectives:
 * 1. Contract Mismatch Audit:
 *    Demonstrate which fields emitted by Android's VoiceTranslateController &
 *    VoxTranslationStateMachine survive Worker's safeContext() and which are stripped.
 *    - Surviving: lookupElapsedMs, requestElapsedMs, providerWaitElapsedMs, totalTranslationStartupMs, isReused, reuseSource.
 *    - Stripped: httpStatus, httpClass, primaryFailure, fallbackCount, state, primaryFailureReason.
 * 2. Canonical Worker Field Validation:
 *    When the canonical key 'responseCode' (503) is provided:
 *    - Level WARNING correctly maps to triage severity 'LOW'.
 *    - Transport HTTP status 503 remains intact in safeContext.
 *    - Audio quality remains strictly uncomputed (undefined).
 * 3. Negative Controls:
 *    - Synthetic DNS failure (UnknownHostException) yields NO HTTP response code.
 *    - Synthetic body marker 'Error 1102' does not manufacture an HTTP status code.
 *    - Fallback attempt event (TRANSLATION_FALLBACK_ATTEMPT) does not prove audible audio recovery.
 */

test('Prompt 163-R16 Gate D.1: Diagnostics Context Ingress Boundary & Key Filtering', () => {
  // Payload generated by Android's VoiceTranslateController.java:2406 + VoxTranslationStateMachine.kt:347
  const actualClientContext = {
    state: 'WAITING_PROVIDER',
    reuseSource: 'NONE',
    lookupElapsedMs: 45,
    requestElapsedMs: 120,
    providerWaitElapsedMs: 310,
    processingElapsedMs: 0,
    audioAttachElapsedMs: 0,
    totalTranslationStartupMs: 475,
    isReused: false,
    primaryFailureReason: 'HTTP 503 for /video-translation/translate',
    fallbackAttempted: true,
    primaryFailure: 'HTTP 503 for /video-translation/translate',
    fallbackCount: 1,
    httpStatus: 503,
    httpClass: '5XX_SERVER_ERROR'
  };

  const filtered = safeContext(actualClientContext);

  // Surviving keys (present in SAFE_CONTEXT_KEYS)
  assert.equal(filtered.lookupElapsedMs, 45, 'lookupElapsedMs must survive');
  assert.equal(filtered.requestElapsedMs, 120, 'requestElapsedMs must survive');
  assert.equal(filtered.providerWaitElapsedMs, 310, 'providerWaitElapsedMs must survive');
  assert.equal(filtered.totalTranslationStartupMs, 475, 'totalTranslationStartupMs must survive');
  assert.equal(filtered.isReused, false, 'isReused must survive');
  assert.equal(filtered.reuseSource, 'NONE', 'reuseSource must survive');

  // Filtered keys (demonstrating contract mismatch with SAFE_CONTEXT_KEYS)
  assert.equal(filtered.httpStatus, undefined, 'httpStatus is stripped by SAFE_CONTEXT_KEYS (expects responseCode)');
  assert.equal(filtered.httpClass, undefined, 'httpClass is stripped by SAFE_CONTEXT_KEYS');
  assert.equal(filtered.primaryFailure, undefined, 'primaryFailure is stripped by SAFE_CONTEXT_KEYS');
  assert.equal(filtered.primaryFailureReason, undefined, 'primaryFailureReason is stripped by SAFE_CONTEXT_KEYS');
  assert.equal(filtered.fallbackCount, undefined, 'fallbackCount is stripped by SAFE_CONTEXT_KEYS');
  assert.equal(filtered.fallbackAttempted, undefined, 'fallbackAttempted is stripped by SAFE_CONTEXT_KEYS');
  assert.equal(filtered.state, undefined, 'state is stripped by SAFE_CONTEXT_KEYS');
});

test('Prompt 163-R16 Gate D.2: Canonical Worker Ingress with responseCode and Dimension Separation', () => {
  const canonicalReport = {
    reportId: 'SYNTHETIC-R16-VOT-CANONICAL-001',
    timestamp: 1730768000000,
    safeRecentEvents: [
      {
        code: 'TRANSLATION_FALLBACK_ATTEMPT',
        level: 'WARNING',
        context: {
          responseCode: 503,
          reason: 'primary_backend_http_503',
          lookupElapsedMs: 45,
          requestElapsedMs: 120,
          providerWaitElapsedMs: 310,
          totalTranslationStartupMs: 475
        }
      }
    ]
  };

  const events = structuredEvents(canonicalReport);
  assert.equal(events.length, 1);
  const ev = events[0];

  // Dimension 1: Triage severity (WARNING -> LOW)
  assert.equal(ev.severity, 'LOW', 'Warning fallback maps to triage priority LOW');

  // Dimension 2: Transport HTTP status
  assert.equal(ev.safeContext.responseCode, 503, 'Transport status must remain 503 in safeContext');

  // Dimension 3: Audio quality uncomputed
  assert.equal(ev.audioQuality, undefined, 'Audio quality must remain uncomputed / absent');
  assert.equal(ev.isAudioDegraded, undefined, 'Degradation flag must remain uncomputed');
});

test('Prompt 163-R16 Gate D.3: Negative Controls (DNS, Error 1102 Body, Fallback != Audible)', () => {
  // Scenario 3A: DNS Failure has no HTTP response code
  const dnsReport = {
    reportId: 'SYNTHETIC-R16-DNS-001',
    timestamp: 1730768100000,
    safeRecentEvents: [
      {
        code: 'TRANSLATION_FALLBACK_ATTEMPT',
        level: 'WARNING',
        context: {
          reason: 'dns_lookup_failed',
          errorCategory: 'dns',
          lookupElapsedMs: 15
        }
      }
    ]
  };

  const dnsEvents = structuredEvents(dnsReport);
  assert.equal(dnsEvents.length, 1);
  assert.equal(dnsEvents[0].safeContext.responseCode, undefined, 'DNS failure must not create HTTP responseCode');
  assert.equal(dnsEvents[0].safeContext.errorCategory, 'dns');

  // Scenario 3B: Body marker 'Error 1102' does not forge transport HTTP status
  const cf1102Report = {
    reportId: 'SYNTHETIC-R16-CF1102-BODY-001',
    timestamp: 1730768200000,
    safeRecentEvents: [
      {
        code: 'TRANSLATION_FALLBACK_ATTEMPT',
        level: 'WARNING',
        context: {
          reason: 'Worker_script_execution_error_1102',
          lookupElapsedMs: 30
        }
      }
    ]
  };

  const cfEvents = structuredEvents(cf1102Report);
  assert.equal(cfEvents.length, 1);
  assert.equal(cfEvents[0].safeContext.responseCode, undefined, 'Error 1102 in body must not manufacture responseCode');

  // Scenario 3C: Fallback attempt does not prove audible audio recovery
  const fbReport = {
    reportId: 'SYNTHETIC-R16-FALLBACK-AUDIO-001',
    timestamp: 1730768300000,
    safeRecentEvents: [
      {
        code: 'TRANSLATION_FALLBACK_ATTEMPT',
        level: 'WARNING',
        context: {
          responseCode: 503,
          lookupElapsedMs: 50
        }
      }
    ]
  };

  const fbEvents = structuredEvents(fbReport);
  assert.equal(fbEvents.length, 1);
  assert.equal(fbEvents[0].event, 'TRANSLATION_FALLBACK_ATTEMPT');
  assert.equal(fbEvents[0].audioAudible, undefined, 'Fallback attempt does not prove audible playback');
  assert.equal(fbEvents[0].audioAttached, undefined, 'Fallback attempt does not prove audio attach');
});
