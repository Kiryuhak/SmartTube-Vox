package com.liskovsoft.smartyoutubetv2.common.vox.subtitles

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import java.io.IOException

/**
 * Unit tests for [VoxSubtitleCoordinator] verifying pickBestSubtitles 1:1 priority,
 * cache keys, binary search cue lookup, and stale generation cancellation.
 */
class VoxSubtitleCoordinatorTest {

    private lateinit var coordinator: VoxSubtitleCoordinator

    @Before
    fun setUp() {
        coordinator = VoxSubtitleCoordinator()
    }

    @Test
    fun testCacheKey_matchesReferenceFormat() {
        val key = coordinator.getSubtitlesCacheKey("abc12345", "en", "ru", true)
        assertEquals("abc12345_en_ru_true", key)

        val keyFallback = coordinator.getSubtitlesCacheKey("xyz789", null, null, false)
        assertEquals("xyz789_auto_ru_false", keyFallback)
    }

    @Test
    fun testPickBestSubtitles_priorityOrdering() {
        val yandexPair = VoxSubtitleDescriptor(
            source = "yandex",
            format = "json",
            language = "ru",
            translatedFromLanguage = "en",
            url = "https://yandex/pair"
        )
        val yandexTarget = VoxSubtitleDescriptor(
            source = "yandex",
            format = "json",
            language = "ru",
            translatedFromLanguage = null,
            url = "https://yandex/target"
        )
        val otherPair = VoxSubtitleDescriptor(
            source = "youtube",
            format = "json",
            language = "ru",
            translatedFromLanguage = "en",
            url = "https://youtube/pair"
        )
        val otherTarget = VoxSubtitleDescriptor(
            source = "youtube",
            format = "json",
            language = "ru",
            translatedFromLanguage = null,
            url = "https://youtube/target"
        )

        // 1. All available -> picks Yandex pair
        val best1 = coordinator.pickBestSubtitles(listOf(otherTarget, yandexTarget, otherPair, yandexPair), "en", "ru")
        assertEquals(yandexPair, best1)

        // 2. Yandex pair omitted -> picks Yandex target
        val best2 = coordinator.pickBestSubtitles(listOf(otherTarget, otherPair, yandexTarget), "en", "ru")
        assertEquals(yandexTarget, best2)

        // 3. Yandex target omitted -> picks other pair
        val best3 = coordinator.pickBestSubtitles(listOf(otherTarget, otherPair), "en", "ru")
        assertEquals(otherPair, best3)

        // 4. Other pair omitted -> picks other target
        val best4 = coordinator.pickBestSubtitles(listOf(otherTarget), "en", "ru")
        assertEquals(otherTarget, best4)
    }

    @Test
    fun testPickBestSubtitles_sameLanguageOriginalPreference() {
        val nativeManual = VoxSubtitleDescriptor(
            source = "youtube",
            format = "json",
            language = "en",
            isAutoGenerated = false,
            url = "https://youtube/en-manual"
        )
        val nativeAuto = VoxSubtitleDescriptor(
            source = "youtube",
            format = "json",
            language = "en",
            isAutoGenerated = true,
            url = "https://youtube/en-auto"
        )
        val yandexSame = VoxSubtitleDescriptor(
            source = "yandex",
            format = "json",
            language = "en",
            url = "https://yandex/en"
        )

        // When source is English and user wants English subtitles, native manual YouTube original comes first
        val best = coordinator.pickBestSubtitles(listOf(yandexSame, nativeAuto, nativeManual), "en", "en")
        assertEquals(nativeManual, best)
    }

    @Test
    fun testFindCueAt_binarySearch() {
        val cues = listOf(
            VoxSubtitleItem("Cue 1", 1000L, 2000L),
            VoxSubtitleItem("Cue 2", 4000L, 2000L),
            VoxSubtitleItem("Cue 3", 7000L, 2000L)
        )

        assertNull(coordinator.findCueAt(cues, 500L))
        assertEquals("Cue 1", coordinator.findCueAt(cues, 1000L)?.text)
        assertEquals("Cue 1", coordinator.findCueAt(cues, 2500L)?.text)
        assertNull(coordinator.findCueAt(cues, 3000L)) // half-open end
        assertNull(coordinator.findCueAt(cues, 3500L))
        assertEquals("Cue 2", coordinator.findCueAt(cues, 5000L)?.text)
        assertEquals("Cue 3", coordinator.findCueAt(cues, 8000L)?.text)
        assertNull(coordinator.findCueAt(cues, 9500L))
    }

    @Test
    fun testLoadSubtitles_cacheHit_avoidsNetwork() {
        var networkCalls = 0
        val mockClient = object : VoxSubtitleCoordinator.SubtitleNetworkClient {
            override fun fetchSubtitles(videoUrl: String, requestLang: String): List<VoxSubtitleDescriptor> {
                networkCalls++
                return listOf(
                    VoxSubtitleDescriptor("yandex", "json", "ru", translatedFromLanguage = "en", url = "http://sub.json")
                )
            }

            override fun fetchSubtitleContent(url: String, format: String): List<VoxSubtitleItem> {
                return listOf(VoxSubtitleItem("Test cue", 1000L, 2000L))
            }
        }

        val testCoordinator = VoxSubtitleCoordinator(mockClient)
        val gen = testCoordinator.nextGeneration()

        val items1 = testCoordinator.loadSubtitlesForVideo("vid1", "https://youtu.be/vid1", "en", "ru", true, gen)
        assertEquals(1, items1.size)
        assertEquals(1, networkCalls)

        // Second call with same cache key should return cached items without network calls
        val items2 = testCoordinator.loadSubtitlesForVideo("vid1", "https://youtu.be/vid1", "en", "ru", true, gen)
        assertEquals(1, items2.size)
        assertEquals(1, networkCalls)
    }

    @Test
    fun testLoadSubtitles_generationCancellation_discardsStale() {
        val mockClient = object : VoxSubtitleCoordinator.SubtitleNetworkClient {
            override fun fetchSubtitles(videoUrl: String, requestLang: String): List<VoxSubtitleDescriptor> {
                return listOf(VoxSubtitleDescriptor("yandex", "json", "ru", url = "http://sub.json"))
            }

            override fun fetchSubtitleContent(url: String, format: String): List<VoxSubtitleItem> {
                return listOf(VoxSubtitleItem("Stale cue", 1000L, 2000L))
            }
        }

        val testCoordinator = VoxSubtitleCoordinator(mockClient)
        val oldGen = testCoordinator.nextGeneration()
        testCoordinator.nextGeneration() // Advance generation, invalidating oldGen

        val items = testCoordinator.loadSubtitlesForVideo("vid2", "https://youtu.be/vid2", "en", "ru", true, oldGen)
        assertTrue(items.isEmpty())
    }

    @Test
    fun testLoadSubtitles_networkErrorNotCached() {
        val mockClient = object : VoxSubtitleCoordinator.SubtitleNetworkClient {
            override fun fetchSubtitles(videoUrl: String, requestLang: String): List<VoxSubtitleDescriptor> {
                throw IOException("Network error")
            }

            override fun fetchSubtitleContent(url: String, format: String): List<VoxSubtitleItem> = emptyList()
        }

        val testCoordinator = VoxSubtitleCoordinator(mockClient)
        val gen = testCoordinator.nextGeneration()

        val items = testCoordinator.loadSubtitlesForVideo("vidError", "https://youtu.be/vidError", "en", "ru", true, gen)
        assertTrue(items.isEmpty())

        // Ensure key was NOT cached
        val key = testCoordinator.getSubtitlesCacheKey("vidError", "en", "ru", true)
        assertNull(testCoordinator.getCachedSubtitles(key))
    }
}
