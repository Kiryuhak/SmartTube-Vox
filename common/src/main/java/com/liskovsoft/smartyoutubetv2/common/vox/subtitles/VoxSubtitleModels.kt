package com.liskovsoft.smartyoutubetv2.common.vox.subtitles

/**
 * Токен отдельного слова с временной меткой.
 */
data class VoxSubtitleToken(
    val text: String,
    val startMs: Long,
    val durationMs: Long
) {
    val endMs: Long get() = startMs + durationMs
}

/**
 * Отдельная строка субтитра.
 */
data class VoxSubtitleItem(
    val text: String,
    val startMs: Long,
    val durationMs: Long,
    val speakerId: String = "0",
    val tokens: List<VoxSubtitleToken> = emptyList()
) {
    val endMs: Long get() = startMs + durationMs
}

/**
 * Дескриптор дорожки субтитров (соответствует parseSubtitleDescriptor в userscript).
 */
data class VoxSubtitleDescriptor(
    val source: String, // "yandex", "youtube"
    val format: String, // "json", "vtt", "srt"
    val language: String,
    val translatedFromLanguage: String? = null,
    val url: String = "",
    val isAutoGenerated: Boolean = false
)

/**
 * Набор распарсенных субтитров дорожки.
 */
data class VoxSubtitlesCollection(
    val format: String = "json",
    val subtitles: List<VoxSubtitleItem> = emptyList()
)
